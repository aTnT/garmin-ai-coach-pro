/**
 * Generate filename for ICS download
 */
export function generateICSFilename(planName: string): string {
  const sanitized = planName
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');

  const timestamp = format(new Date(), 'yyyy-MM-dd');

  return `${sanitized}-${timestamp}.ics`;
}
